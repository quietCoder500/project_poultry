from django.apps import AppConfig
import importlib
import pkgutil


class GrowthConfig(AppConfig):
    name = "growth"

    def ready(self) -> None:
        """
        This is not my code. This code was generated by Gemini Flash 3.6.
        It imports all the widgets for the progress report generator so that they are registered
        with the generators ALL_GENERATORS list
        """
        import growth.generators as generators_pkg

        for _, module_name, _ in pkgutil.iter_modules(generators_pkg.__path__):
            importlib.import_module(f"growth.generators.{module_name}")
        return super().ready()
